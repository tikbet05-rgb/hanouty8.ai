CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.store_products (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 160),
  description TEXT CHECK (description IS NULL OR char_length(description) <= 5000),
  sku TEXT CHECK (sku IS NULL OR char_length(sku) <= 80),
  price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency IN ('MAD', 'USD', 'EUR', 'GBP')),
  stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'archived')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (owner_id, sku)
);

CREATE TABLE IF NOT EXISTS public.store_orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  order_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  customer_name TEXT NOT NULL CHECK (char_length(customer_name) BETWEEN 1 AND 160),
  customer_email TEXT NOT NULL CHECK (char_length(customer_email) <= 320),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'paid', 'fulfilled', 'cancelled', 'refunded')),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency IN ('MAD', 'USD', 'EUR', 'GBP')),
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
  shipping_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (shipping_amount >= 0),
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
  total_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  items JSONB NOT NULL CHECK (jsonb_typeof(items) = 'array'),
  payment_provider TEXT,
  provider_reference TEXT,
  payment_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (status <> 'paid' OR (payment_verified_at IS NOT NULL AND provider_reference IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.store_expenses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  description TEXT NOT NULL CHECK (char_length(description) BETWEEN 1 AND 500),
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  currency TEXT NOT NULL CHECK (currency IN ('MAD', 'USD', 'EUR', 'GBP')),
  expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
  source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'provider')),
  provider_reference TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS store_products_owner_created_idx ON public.store_products(owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS store_orders_owner_created_idx ON public.store_orders(owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS store_orders_owner_status_idx ON public.store_orders(owner_id, status);
CREATE INDEX IF NOT EXISTS store_expenses_owner_date_idx ON public.store_expenses(owner_id, expense_date DESC);

ALTER TABLE public.store_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_expenses ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "owners manage their products" ON public.store_products;
CREATE POLICY "owners manage their products" ON public.store_products
  FOR ALL TO authenticated USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

DROP POLICY IF EXISTS "owners read their orders" ON public.store_orders;
CREATE POLICY "owners read their orders" ON public.store_orders
  FOR SELECT TO authenticated USING (owner_id = auth.uid());

DROP POLICY IF EXISTS "owners create pending orders" ON public.store_orders;
CREATE POLICY "owners create pending orders" ON public.store_orders
  FOR INSERT TO authenticated WITH CHECK (owner_id = auth.uid() AND status = 'pending' AND total_amount = 0 AND subtotal = 0 AND payment_verified_at IS NULL AND provider_reference IS NULL);

DROP POLICY IF EXISTS "owners read their expenses" ON public.store_expenses;
CREATE POLICY "owners read their expenses" ON public.store_expenses
  FOR SELECT TO authenticated USING (owner_id = auth.uid());

REVOKE ALL ON public.store_products, public.store_orders, public.store_expenses FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.store_products TO authenticated;
GRANT SELECT, INSERT ON public.store_orders TO authenticated;
GRANT SELECT ON public.store_expenses TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.store_orders_order_number_seq TO authenticated;

CREATE OR REPLACE FUNCTION public.set_store_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = NOW(); RETURN NEW; END;
$$;

DROP TRIGGER IF EXISTS store_products_updated_at ON public.store_products;
CREATE TRIGGER store_products_updated_at BEFORE UPDATE ON public.store_products
  FOR EACH ROW EXECUTE FUNCTION public.set_store_updated_at();
DROP TRIGGER IF EXISTS store_orders_updated_at ON public.store_orders;
CREATE TRIGGER store_orders_updated_at BEFORE UPDATE ON public.store_orders
  FOR EACH ROW EXECUTE FUNCTION public.set_store_updated_at();
